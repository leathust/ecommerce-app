<?php

namespace App\Services;

use App\Models\Product;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Storage;
use Throwable;

class ProductImageService
{
    public function save(Product $product, array $data): void
    {
        $createdPaths = [];
        $deletedPaths = [];
        try {
            DB::transaction(function () use ($product, $data, &$createdPaths, &$deletedPaths): void {
                $product->fill(collect($data)->except(['images', 'image_meta', 'delete_images', 'primary_image', 'new_alt'])->all())->save();
                // Serialize image changes for this product within the transaction.
                Product::whereKey($product->id)->lockForUpdate()->first();
                foreach ($product->images()->whereIn('id', $data['delete_images'] ?? [])->get() as $image) {
                    $deletedPaths[] = $image->image_url;
                    $image->delete();
                }
                foreach ($data['image_meta'] ?? [] as $id => $metadata) {
                    $product->images()->whereKey($id)->update($metadata);
                }
                $newIds = [];
                $sortOrder = (int) $product->images()->max('sort_order');
                foreach ($data['images'] ?? [] as $index => $upload) {
                    $path = $upload->store((string) $product->id, 'product_images');
                    $createdPaths[] = $path;
                    $image = $product->images()->create([
                        'image_url' => $path,
                        'alt_text' => $data['new_alt'][$index] ?? null,
                        'sort_order' => ++$sortOrder,
                        'is_primary' => false,
                    ]);
                    $newIds[$index] = $image->id;
                }
                $choice = $data['primary_image'] ?? null;
                $primaryId = null;
                if ($choice) {
                    [$type, $id] = explode(':', $choice, 2);
                    $primaryId = $type === 'new' ? ($newIds[$id] ?? null) : (int) $id;
                }
                $primaryId ??= $product->images()->where('is_primary', true)->value('id');
                $primaryId ??= $product->images()->orderBy('sort_order')->orderBy('id')->value('id');
                $product->images()->update(['is_primary' => false]);
                if ($primaryId) {
                    $product->images()->whereKey($primaryId)->update(['is_primary' => true]);
                }
            });
        } catch (Throwable $exception) {
            $this->deleteFiles($createdPaths);
            throw $exception;
        }
        // Only remove old files after database changes have committed.
        $this->deleteFiles($deletedPaths);
    }

    public function deleteFiles(array $paths): void
    {
        foreach ($paths as $path) {
            // Only manage files generated by this uploader; never delete arbitrary legacy URLs.
            if (preg_match('~^\d+/[a-zA-Z0-9]+\.(?:jpg|jpeg|png|webp)$~', $path)) {
                try {
                    Storage::disk('product_images')->delete($path);
                } catch (Throwable $exception) {
                    report($exception);
                }
            }
        }
    }
}
